def build_universe(ref_date):
    if FIXED_UNIVERSE:
        return [to_jq(c) for c in FIXED_UNIVERSE]
    pool = get_index_stocks('000985.XSHG', ref_date)     # 中证全指
    keep = []
    for s in pool:
        info = get_security_info(s)
        if info is None:
            continue
