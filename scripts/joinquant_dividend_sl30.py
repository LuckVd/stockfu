def to_jq(code):
    """6 位裸代码 → 聚宽后缀代码(沪 .XSHG / 深 .XSHE / 北交所 .BJ)。"""
    c = str(code).strip().zfill(6)
    if c[0] == '6':                 # 60x/68x 沪市
        return c + '.XSHG'
    if c[0] in ('0', '3'):          # 00x/30x 深市
        return c + '.XSHE'
    return c + '.BJ'                # 8x/4x 北交所


# ===== 取价归一:聚宽 get_price 单字段返回结构随版本漂移(dict{DF}/DF/Series),统一归一。 =====
def _last_close(codes, ref_date, fq):
    """→ {code: 末日收盘 float}。count=2 避免单日 Series 退化。"""
    out = {}
    if not codes:
        return out
    px = get_price(codes, end_date=ref_date, count=2, frequency='daily',
                   fields=['close'], fq=fq, panel=False)
    obj = px['close'] if isinstance(px, dict) and 'close' in px else px
    row = obj.iloc[-1] if hasattr(obj, 'columns') else obj   # DF→末行Series / Series
    for c in codes:
        if c in getattr(row, 'index', ()):
            v = row[c]
            if v is not None and v == v and v > 0:           # v==v 排除 NaN
                out[c] = float(v)
    return out


def _close_panel(codes, ref_date, count, fq):
    """→ {code: pd.Series(收盘, index=date)}。count>1 返回稳定 DataFrame。"""
    out = {}
    if not codes:
        return out
    px = get_price(codes, end_date=ref_date, count=count, frequency='daily',
                   fields=['close'], fq=fq, panel=False)
    obj = px['close'] if isinstance(px, dict) and 'close' in px else px
    if hasattr(obj, 'columns'):                              # DataFrame(date × codes)
        for c in codes:
            if c in obj.columns:
                out[c] = obj[c].dropna()
    return out


# ============================ 因子(口径逐行对齐本地) ============================
def factor_dividend(codes, ref_date):
    """红利 score:TTM 每股税前现金分红 ÷ 不复权收盘 × 100(封顶 20%)。
    分红取 finance.STK_DIVIDEND.a_cash_div_tax(每股税前现金股利,元),ex_date 近 365 天;
    分母 _last_close(fq=None) 不复权(命门)。≥5%→+20;1~5% 线性;<1%→0。
    注:STK_DIVIDEND.code 带后缀(聚宽示例 '000001.XSHE');若返回空可能是 code 格式不符,
    把 .in_(list(closes)) 换成 [c.split('.')[0] for c in closes] 再试。"""
    scores = {}
    if not codes:
        return scores
    closes = _last_close(codes, ref_date, fq=None)           # 分母不复权
    if not closes:
        return scores
    year_ago = ref_date - timedelta(days=365)
    q = query(finance.STK_DIVIDEND).filter(
        finance.STK_DIVIDEND.code.in_(list(closes)),        # 带后缀
        finance.STK_DIVIDEND.ex_date >= year_ago,
        finance.STK_DIVIDEND.ex_date <= ref_date)
    df = finance.run_query(q)
    ttm = {}
    if df is not None and len(df):
        for c, grp in df.groupby('code'):
            v = grp['a_cash_div_tax'].sum()                 # 近365天每股税前现金股利合计
            if v and v > 0:
                ttm[c] = float(v)
    for jqc, close in closes.items():
        cash = ttm.get(jqc, 0.0)                            # code 带后缀,key 对齐
        if cash <= 0:
            scores[jqc] = 0.0
            continue
        y = min(cash / close * 100, YIELD_CAP)
        if y >= HIGH_YIELD:
            scores[jqc] = 20.0
        elif y >= 1.0:
            scores[jqc] = min(20 * (y - 1) / (HIGH_YIELD - 1), 20.0)
        else:
            scores[jqc] = 0.0
    return scores


def factor_low_vol(codes, ref_date):
    """低波 score:近 LV_WINDOW 日收益 std 在近 LV_HIST 滚动 std 序列的时序分位。
    <30 分位→正分 20×(1-pct/30);>70→负分;否则 0。"""
    scores = {}
    panel = _close_panel(codes, ref_date, LV_HIST + LV_WINDOW, fq='pre')
    for c in codes:
        s = panel.get(c)
        if s is None or len(s) < LV_WINDOW + 1:
            continue
        rets = (s / s.shift(1) - 1).dropna()
        stds = rets.rolling(LV_WINDOW).std().dropna()
        if len(stds) < 10:
            continue
        cur = stds.iloc[-1]
        pct = (stds < cur).sum() / len(stds) * 100     # 时序分位(平均秩近似)
        if pct < 30:
            scores[c] = 20 * (1 - pct / 30)
        elif pct > 70:
            scores[c] = -20 * (1 - (100 - pct) / 30)
        else:
            scores[c] = 0.0
    return scores


def factor_value(codes, ref_date):
    """价值 score:当前 PE 在近 VAL_YEARS 年时序分位。
    <20 分位→正分;>80→负分;否则 0。 FIXME-JQ: PE 历史用月采样近似(够分位)。"""
    scores = {}
    # 当前 PE
    cur = get_fundamentals(query(valuation.code, valuation.pe_ratio).filter(
        valuation.code.in_(codes)), date=ref_date)
    cur = {r['code']: r['pe_ratio'] for r in cur.to_dict('records')
           if r['pe_ratio'] and r['pe_ratio'] > 0}
    # 历史月采样 PE 序列(每个 code 一条;近 5 年每月一点,足够做时序分位)
    hist = {c: [] for c in cur}
    start = ref_date - timedelta(days=VAL_YEARS * 365)
    months = [start + timedelta(days=30 * i) for i in range(0, VAL_YEARS * 12 + 1)]
    for d in months:
        df = get_fundamentals(query(valuation.code, valuation.pe_ratio).filter(
            valuation.code.in_(list(cur.keys()))), date=d)
        for r in df.to_dict('records'):
            if r['pe_ratio'] and r['pe_ratio'] > 0 and r['code'] in hist:
                hist[r['code']].append(float(r['pe_ratio']))
    for c, pe in cur.items():
        h = sorted(hist.get(c, []))
        if len(h) < 10:
            continue
        pct = sum(1 for x in h if x < pe) / len(h) * 100
        if pct < 20:
            scores[c] = 20 * (1 - pct / 20)
        elif pct > 80:
            scores[c] = -20 * (1 - (100 - pct) / 20)
        else:
            scores[c] = 0.0
    return scores


